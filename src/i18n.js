let lang = (() => {
  try {
    const s = localStorage.getItem('gp-lang');
    if (s === 'zh' || s === 'en') return s;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
})();
const listeners = new Set();

export const getLang = () => lang;

export function t(key, vars) {
  let s = (dict[lang] && dict[lang][key]) ?? dict.en[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const v = t(el.dataset.i18nTitle);
    el.title = v;
    el.setAttribute('aria-label', v);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  document.title = t(document.body.dataset.titleKey || 'app.title');
}

export function setLang(l) {
  lang = l;
  try { localStorage.setItem('gp-lang', l); } catch {}
  applyI18n();
  listeners.forEach((f) => f(l));
}

export function onLang(fn) { listeners.add(fn); }

export function initLangToggle(btn) {
  const paint = () => (btn.textContent = lang === 'zh' ? 'EN' : '中文');
  btn.addEventListener('click', () => setLang(lang === 'zh' ? 'en' : 'zh'));
  onLang(paint);
  paint();
}
